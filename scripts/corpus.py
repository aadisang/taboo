"""Audit editorial cards, build the runtime deck, or fetch real-word candidates.

No network access is needed for audit/build. Candidate downloads are pinned by hash.
"""

import argparse
import collections
import hashlib
import json
from pathlib import Path
import re
import unicodedata
import urllib.request

ROOT = Path(__file__).resolve().parent.parent
CORPUS = ROOT / "corpus"
CATEGORIES = {
    "home", "food", "nature", "science", "travel",
    "work", "arts", "leisure", "people", "actions",
}


def normalized(text):
    return "".join(c for c in unicodedata.normalize("NFKD", text).upper() if c.isalnum())


def read_legacy_cards():
    text = (ROOT / "src/data/taboo-cards.ts").read_text()
    # The legacy deck is a literal tuple list. Runtime integration is checked in Vitest.
    return [
        (word, json.loads(f"[{bans}]"))
        for word, bans in re.findall(r'\[\s*"([^"]+)",\s*\[([^\]]+)\]\s*,?\s*\]', text)
    ]


def audit():
    rows = json.loads((CORPUS / "expansion.json").read_text())
    if not isinstance(rows, list) or not rows:
        raise ValueError("Expansion must be a nonempty array")
    seen = {normalized(word) for word, _ in read_legacy_cards()}
    for row in rows:
        if not isinstance(row, list) or len(row) != 4:
            raise ValueError(f"Expected [category, target, five bans, two routes]: {row!r}")
        category, word, bans, routes = row
        if not isinstance(category, str) or category not in CATEGORIES:
            raise ValueError(f"Unknown category: {category!r}")
        if not isinstance(word, str) or not word or word != word.strip().upper():
            raise ValueError(f"Bad target: {word!r}")
        if normalized(word) in seen:
            raise ValueError(f"Duplicate target: {word}")
        seen.add(normalized(word))
        if not isinstance(bans, list) or len(bans) != 5:
            raise ValueError(f"{word}: expected five bans")
        if any(not isinstance(ban, str) or not ban or ban != ban.strip().upper() for ban in bans):
            raise ValueError(f"{word}: malformed ban")
        if len({normalized(ban) for ban in bans}) != 5:
            raise ValueError(f"{word}: repeated ban")
        if normalized(word) in {normalized(ban) for ban in bans}:
            raise ValueError(f"{word}: self-ban")
        target_parts = set(re.findall(r"[A-Z]+", word))
        if any(ban in target_parts for ban in bans):
            raise ValueError(f"{word}: wasted ban on a target component")
        if not isinstance(routes, list) or len(routes) != 2:
            raise ValueError(f"{word}: expected two escape routes")
        if any(not isinstance(route, str) or len(route.split()) < 5 for route in routes):
            raise ValueError(f"{word}: escape routes need actual descriptions")
        if normalized(routes[0]) == normalized(routes[1]):
            raise ValueError(f"{word}: identical escape routes")
        for route in routes:
            # Whole words and simple suffixes only. This is not an English lemmatizer.
            for ban in [word, *bans]:
                pattern = r"\b" + re.escape(ban) + r"(?:s|es|ed|ing)?\b"
                if re.search(pattern, route, flags=re.IGNORECASE):
                    raise ValueError(f"{word}: route uses {ban}: {route}")
    print(f"Editorial audit: {len(rows)} cards, {len(rows) * 2} written escape routes")
    print("Categories:", dict(sorted(collections.Counter(row[0] for row in rows).items())))
    return rows


def build(rows):
    lines = [
        "// Generated by vp run corpus:build from corpus/expansion.json. Do not edit.",
        'import type { TabooCardTuple } from "./taboo-cards";',
        "",
        "export const expansionCardTuples = [",
    ]
    lines.extend("  " + json.dumps([word, bans], ensure_ascii=False) + "," for _, word, bans, _ in rows)
    lines.append("] as const satisfies readonly TabooCardTuple[];")
    (ROOT / "src/data/expansion-cards.ts").write_text("\n".join(lines) + "\n")
    print("Generated src/data/expansion-cards.ts")


def candidates(rows):
    source = json.loads((CORPUS / "eff-source.json").read_text())
    cache = CORPUS / ".cache/eff-large-wordlist.txt"
    if cache.exists():
        content = cache.read_bytes()
    else:
        with urllib.request.urlopen(source["url"], timeout=30) as response:
            content = response.read()
    if hashlib.sha256(content).hexdigest() != source["sha256"]:
        raise ValueError("EFF source checksum changed. Review the source before updating its pin.")
    pairs = [line.split() for line in content.decode("utf-8").splitlines()]
    if len(pairs) != source["entries"] or any(
        len(pair) != 2 or not re.fullmatch(r"[1-6]{5}", pair[0]) for pair in pairs
    ):
        raise ValueError("Unexpected EFF wordlist format")
    words = [word.upper() for _, word in pairs]
    if len(set(words)) != len(words):
        raise ValueError("Duplicate EFF entries")
    cache.parent.mkdir(parents=True, exist_ok=True)
    cache.write_bytes(content)
    existing = {normalized(word) for word, _ in read_legacy_cards()}
    existing.update(normalized(word) for _, word, _, _ in rows)
    remaining = []
    for word in words:
        key = normalized(word)
        if key not in existing:
            remaining.append(word)
            existing.add(key)
    result = {
        "source": source,
        "status": "unreviewed; not loaded by the game",
        "warning": "Dictionary membership does not establish familiarity, appropriateness, or playability.",
        "words": remaining,
    }
    destination = CORPUS / "candidates.json"
    destination.write_text(json.dumps(result, indent=2) + "\n")
    source_words = set(words)
    attested = sum(word in source_words for _, word, _, _ in rows)
    print(f"EFF: {len(words)} real-word entries; {attested} of our new targets attested exactly")
    print(f"Wrote {len(remaining)} unreviewed candidates to {destination.relative_to(ROOT)}")


if __name__ == "__main__":
    parser = argparse.ArgumentParser(description=__doc__)
    parser.add_argument("command", choices=["audit", "build", "candidates"])
    command = parser.parse_args().command
    reviewed = audit()
    if command == "build":
        build(reviewed)
    elif command == "candidates":
        candidates(reviewed)
